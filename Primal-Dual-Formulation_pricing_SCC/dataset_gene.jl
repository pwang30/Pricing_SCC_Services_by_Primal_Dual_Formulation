function dataset_gene(nᵥ,Gᵥ,IBG)  

#-----------------------------------Calculation of SCC constraints----------------------------------
    numnodes=30                         # number of nodes
    num_nᵥ=length(nᵥ)                   # number of intervals in nᵥ
    num_VSG=length(Gᵥ)                  # number of nodes where VSGs are located
    num_IBG=length(IBG)                 # number of nodes where IBGs are located
    #            Bus Number	     x1	      x2
    SGpara=[
                   2	       0.0846	
                   3	       0.0799	
                   4	       0.0758	
                   5	       0.0731	
                   27	       0.0519	
                   30	       0.0523	]  # buses where SGs are located
    VSGpara= [ 0.0483]

    Y_SGs = zeros(size(SGpara,1), size(SGpara,2)-1)    # define ADMITTANCE MATRIX of the SGs, buses:2,3,4,5,27,30
    
    Yₗᵢₙₑ=admittance_matrix_calculation(numnodes)   # calculate the ADMITTANCE MATRIX of the network

    for k in 1:size(SGpara,1)                      # calculate the ADMITTANCE MATRIX of the SGs
        for j in 2:size(SGpara,2)
            Y_SGs[k, j-1] = 1/SGpara[k, j]/10      
        end           
    end 
    
    Y_VSGs=1/VSGpara[1]/10

#------------Evaluate the impedance in all Ω scenarios
    Ω=2^(length(SGpara[:,2:end]))*num_nᵥ^(num_VSG)
    #Ω=2^(length(SGpara[:,2:end]))*num_nᵥ^(num_VSG)                   # Dimension of the data set, which is generated by evaluating impedance ratio at different operating conditions
    zᵟ_c=zeros(Ω,2)                 # Impedance ratio in all Ω scenarios, for each row, the zᵟ_c is   [z₂₃²⁴, z₂₄²³, z₂₃¹, z₂₄¹]
    ηm=zeros(Ω,(binomial(length(SGpara[:,2:end]),2)+ length(SGpara[:,2:end])*num_VSG))      # Interactions between each two (V)SGs : 12 SGs , 1 VSG >>>> 66+12
    
    combinations = collect(product(0:1, repeat([0:1], length(SGpara[:,2:end])-1)...))    # generate all combinations of 12 SGs
    matrix = hcat([collect(combo) for combo in combinations]...)  # convert the combination to a matrix
    matrix = transpose(matrix)                                    # transpose the matrix
    u_gc_α_gv=zeros(Ω,length(SGpara[:,2:end])+num_VSG)

    index=1
    for j in 1:num_nᵥ
        for i in 1:size(matrix,1)
            u_gc_α_gv[index,1:6] = matrix[i,:]
            u_gc_α_gv[index,7] = nᵥ[j]
            index += 1
        end
    end

    for k in 1:Ω    # generate ηm by calculating the product of each pair of (V)SGs in all Ω scenarios
        index = 1
        for i in 1:length(SGpara[:,2:end])-1
            for j in i+1:length(SGpara[:,2:end])
                ηm[k,index] = u_gc_α_gv[k,i] * u_gc_α_gv[k,j]
                index += 1
            end
        end
        for i in 1:length(SGpara[:,2:end])
            ηm[k,15+i]=u_gc_α_gv[k,7]*u_gc_α_gv[k,i]
        end
    end

    matrix_ω=hcat(u_gc_α_gv,ηm)

    
    status_SGs = zeros(1, length(SGpara[:,2:end]))      # define status of SGs
    status_VSG = zeros(1, num_VSG)                      # define status of VSG
    Y_SGs_with_status = zeros(numnodes, numnodes)       # define the ADMITTANCE MATRIX for SGs status
    Y_VSGs_with_status = zeros(numnodes, numnodes)       # define the ADMITTANCE MATRIX for VSG status
    Y_total = zeros(numnodes, numnodes)                 # define the total ADMITTANCE MATRIX
    Z = zeros(numnodes, numnodes)                       # define the impedance matrix
    
    for k in 1:Ω
        status_SGs = matrix_ω[k, 1:length(SGpara[:,2:end])]                                     # status of SGs
        status_VSG = matrix_ω[k, 7]   # status of VSG
        Y_SGs_with_status .= 0                                                                  # reset Y_SGs_with_status matrix
        Y_VSGs_with_status .= 0 

        for i in 1:length(SGpara[:,2:end])
            Y_SGs_with_status[Int(SGpara[i, 1]), Int(SGpara[i, 1])] = Y_SGs[i] * status_SGs[i]  # status of SGs
        end

        Y_VSGs_with_status[Gᵥ[1],Gᵥ[1]]=Y_VSGs *status_VSG
        
        Y_total .= Yₗᵢₙₑ +Y_SGs_with_status +Y_VSGs_with_status    # calculate the total ADMITTANCE MATRIX
        Z .= inv(Y_total)                        # calculate the IMPEDANCE MATRIX
    
        zᵟ_c[k,1] = 1/Z[IBG[1],IBG[1]] 
        zᵟ_c[k,2] = 1/Z[IBG[2],IBG[2]] 
    end
    
return zᵟ_c, matrix_ω
    
    
end

